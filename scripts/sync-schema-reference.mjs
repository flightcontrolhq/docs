import {mkdirSync, readFileSync, writeFileSync} from "node:fs";
import path from "node:path";

const root = process.cwd();
const sourceDir = path.resolve(
  root,
  "../flightcontrol/packages/schemas/schema_reference/docs",
);
const targetDir = path.join(root, "snippets/schema-reference");

const files = ["pipeline", "module", "project-config"];

mkdirSync(targetDir, {recursive: true});

for (const name of files) {
  const sourcePath = path.join(sourceDir, `${name}.md`);
  const targetPath = path.join(targetDir, `${name}.mdx`);
  const content = readFileSync(sourcePath, "utf8").trimEnd();

  writeFileSync(
    targetPath,
    `{/* Generated by scripts/sync-schema-reference.mjs from ../flightcontrol/packages/schemas/schema_reference/docs/${name}.md. Do not edit by hand. */}\n\n${content}\n`,
  );
}
